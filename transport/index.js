// Слой транспорта: единственное место в проекте, которое знает,
// как байты на самом деле ходят по сети. Логика чата работает только
// с абстрактным «соединением», описанным ниже, и не импортирует сетевые библиотеки.
//
// Транспорт экспортирует две функции:
//
//   listen({ port, onConnection }) → Promise<TransportServer>
//     Запускает сервер на всех сетевых интерфейсах. Для каждого нового
//     клиента вызывает onConnection(connection). Промис отклоняется, если
//     порт занят (error.code === 'EADDRINUSE') или недоступен.
//
//   connect({ host, port }) → Promise<Connection>
//     Подключается к серверу. Промис отклоняется при ECONNREFUSED,
//     ETIMEDOUT, ENOTFOUND и т. п.
//
// TransportServer:
//   port            — фактический порт (полезно, если слушали порт 0)
//   close()         → Promise<void>, перестаёт принимать новые подключения
//
// Connection (EventEmitter):
//   remoteAddress   — адрес собеседника вида "ip:port", для логов
//   send(text)      — отправить одно сообщение (строку)
//   close()         — штатно закрыть соединение
//   'message' (text)  — пришло одно целое сообщение
//   'close' (error?)  — соединение закрыто; error есть, если это был обрыв
//
// Событие 'error' наружу не выходит: транспорт сам перехватывает ошибки
// сокета и передаёт их в 'close'. Поэтому никакое действие клиента
// не может уронить процесс через «unhandled 'error' event».

export { connect, listen } from './ws.js';
